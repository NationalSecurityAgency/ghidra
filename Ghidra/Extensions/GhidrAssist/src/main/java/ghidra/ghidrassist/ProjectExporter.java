package ghidra.ghidrassist;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.listing.Program;
import ghidra.util.task.TaskMonitor;

/**
 * Writes a buildable-ish C project reconstruction of the current program.
 *
 * <p><b>Honest limits:</b> the Ghidra decompiler's C output is a lossy
 * reconstruction, not the original source. Even after Claude cleans each
 * function, the exported project will not compile unmodified for non-trivial
 * binaries, and even once it does, the resulting binary will not match
 * byte-for-byte. This is a starting point for manual porting, not a
 * decompile-and-rebuild pipeline.
 */
public final class ProjectExporter {

	private static final Pattern CODE_FENCE =
		Pattern.compile("```(?:c|C)?\\s*\\n([\\s\\S]*?)```", Pattern.MULTILINE);

	private ProjectExporter() {
	}

	public static Result export(Program program, Path outputDir, boolean claudeClean,
			ClaudeClient claude, ClaudeOptions options, TaskMonitor monitor) throws IOException {

		Path srcDir = outputDir.resolve("src");
		Files.createDirectories(srcDir);

		List<String> prototypes = new ArrayList<>();
		int ok = 0, failed = 0;
		FunctionIterator iter = program.getFunctionManager().getFunctions(true);
		int total = program.getFunctionManager().getFunctionCount();
		monitor.initialize(total);

		for (Function fn : iter) {
			if (monitor.isCancelled()) {
				break;
			}
			monitor.incrementProgress(1);
			if (fn.isExternal() || fn.isThunk()) {
				continue;
			}
			monitor.setMessage("Decompiling " + fn.getName());
			String c = DecompilerHelper.decompile(program, fn, monitor);
			if (c == null) {
				failed++;
				continue;
			}

			String body = c;
			if (claudeClean && options.isConfigured()) {
				monitor.setMessage("Claude cleaning " + fn.getName());
				String cleaned = cleanWithClaude(claude, options, c);
				if (cleaned != null) {
					body = cleaned;
				}
			}

			String safeName = sanitize(fn.getName()) + "_" +
				Long.toHexString(fn.getEntryPoint().getOffset());
			Path file = srcDir.resolve(safeName + ".c");
			Files.writeString(file, buildFileHeader(fn) + body + "\n",
				StandardCharsets.UTF_8);
			prototypes.add(extractPrototype(body, fn.getName()));
			ok++;
		}

		writeHeader(outputDir, program, prototypes);
		writeMakefile(outputDir, program);
		writeReadme(outputDir, program, ok, failed);
		return new Result(outputDir, ok, failed);
	}

	private static String cleanWithClaude(ClaudeClient claude, ClaudeOptions opts, String raw) {
		String prompt = """
			Rewrite the following decompiler output as idiomatic, portable C that would \
			plausibly compile with gcc. Preserve semantics. Keep the same function name \
			and signature. Return ONLY the function in a ```c``` fenced block.

			```c
			%s
			```
			""".formatted(raw);
		try {
			String resp = claude.complete(opts, List.of(ClaudeMessage.user(prompt)));
			Matcher m = CODE_FENCE.matcher(resp);
			if (m.find()) {
				return m.group(1);
			}
			return resp;
		}
		catch (Exception e) {
			return null;
		}
	}

	private static String buildFileHeader(Function fn) {
		return "/* Auto-generated by GhidrAssist from Ghidra decompilation.\n" +
			" * Function: " + fn.getName() + "\n" +
			" * Entry:    " + fn.getEntryPoint() + "\n" +
			" * This is a reconstruction, not original source. Review before trusting.\n" +
			" */\n#include \"program.h\"\n\n";
	}

	private static String extractPrototype(String body, String fallbackName) {
		String[] lines = body.split("\\r?\\n");
		for (String line : lines) {
			String t = line.trim();
			if (t.isEmpty() || t.startsWith("/*") || t.startsWith("*") || t.startsWith("//")) {
				continue;
			}
			int paren = t.indexOf('(');
			int brace = t.indexOf('{');
			if (paren > 0 && (brace < 0 || paren < brace)) {
				String sig = brace > 0 ? t.substring(0, brace).trim() : t;
				if (sig.endsWith(";")) {
					sig = sig.substring(0, sig.length() - 1);
				}
				if (!sig.endsWith(")")) {
					int close = sig.lastIndexOf(')');
					if (close > 0) {
						sig = sig.substring(0, close + 1);
					}
				}
				return sig + ";";
			}
		}
		return "/* prototype for " + fallbackName + " not recovered */";
	}

	private static void writeHeader(Path outputDir, Program program, List<String> prototypes)
			throws IOException {
		StringBuilder sb = new StringBuilder();
		sb.append("/* Auto-generated by GhidrAssist. */\n");
		sb.append("#ifndef GHIDRASSIST_PROGRAM_H\n#define GHIDRASSIST_PROGRAM_H\n\n");
		sb.append("#include <stddef.h>\n#include <stdint.h>\n#include <stdbool.h>\n");
		sb.append("#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n");
		sb.append("/* Source program: ")
				.append(program.getName())
				.append(" */\n\n");
		for (String p : prototypes) {
			sb.append(p).append('\n');
		}
		sb.append("\n#endif\n");
		Files.writeString(outputDir.resolve("program.h"), sb.toString(), StandardCharsets.UTF_8);
	}

	private static void writeMakefile(Path outputDir, Program program) throws IOException {
		String target = sanitize(program.getName());
		String mk = ""
			+ "# Auto-generated by GhidrAssist.\n"
			+ "# This Makefile is a best-effort scaffold. Expect to edit it.\n"
			+ "CC      ?= gcc\n"
			+ "CFLAGS  ?= -O2 -g -Wall -Wextra -I.\n"
			+ "LDFLAGS ?=\n"
			+ "SRC     := $(wildcard src/*.c)\n"
			+ "OBJ     := $(SRC:.c=.o)\n"
			+ "TARGET  := " + target + "\n\n"
			+ "all: $(TARGET)\n\n"
			+ "$(TARGET): $(OBJ)\n"
			+ "\t$(CC) $(CFLAGS) -o $@ $^ $(LDFLAGS)\n\n"
			+ "clean:\n"
			+ "\trm -f $(OBJ) $(TARGET)\n\n"
			+ ".PHONY: all clean\n";
		Files.writeString(outputDir.resolve("Makefile"), mk, StandardCharsets.UTF_8);
	}

	private static void writeReadme(Path outputDir, Program program, int ok, int failed)
			throws IOException {
		String msg = ""
			+ "# " + program.getName() + " — reconstructed by GhidrAssist\n\n"
			+ "- Functions reconstructed: " + ok + "\n"
			+ "- Functions skipped or failed: " + failed + "\n\n"
			+ "## Honest expectations\n\n"
			+ "This directory is **a decompiler reconstruction**, not the program's\n"
			+ "original source. For anything beyond trivial binaries you should\n"
			+ "expect:\n\n"
			+ "1. The code **will not build** with `make` out of the box. The\n"
			+ "   decompiler's casts, inlined intrinsics, and PCODE artefacts have\n"
			+ "   no portable C equivalent and require manual translation.\n"
			+ "2. Even once it compiles, the resulting binary **will not be\n"
			+ "   identical** to the one you decompiled. Register allocation,\n"
			+ "   calling conventions, alignment, link order, and compiler flags\n"
			+ "   all differ.\n"
			+ "3. Any identifiers restored by the LLM are **hypotheses**. Treat them\n"
			+ "   accordingly.\n\n"
			+ "Use this as a starting point for manual porting, not as a push-button\n"
			+ "decompile-and-rebuild pipeline.\n";
		Files.writeString(outputDir.resolve("README.md"), msg, StandardCharsets.UTF_8);
	}

	private static String sanitize(String name) {
		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < name.length(); i++) {
			char c = name.charAt(i);
			boolean ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
				(c >= '0' && c <= '9') || c == '_';
			sb.append(ok ? c : '_');
		}
		if (sb.length() == 0 || Character.isDigit(sb.charAt(0))) {
			sb.insert(0, '_');
		}
		return sb.toString();
	}

	public record Result(Path outputDir, int reconstructed, int failed) {
	}
}
